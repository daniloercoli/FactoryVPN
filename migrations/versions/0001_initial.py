def upgrade():
    # Refuse to adopt or partially rewrite an unrelated/older schema.
    existing = (
        set(inspect(op.get_bind()).get_table_names()) - {"alembic_version"}
        if not context.is_offline_mode()
        else set()
    )
    if existing:
        raise RuntimeError("FactoryVPN initial schema requires an empty database schema")
    for statement in STATEMENTS:
        op.execute(statement)


def downgrade():
    raise RuntimeError("Initial schema removal is not an application rollback")
